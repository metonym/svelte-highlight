// Several of these contain `-` or `.` (`on-failure`, `multi-user.target`),
// so the keyword tokenizer must include those characters (see `$pattern`):
// with the default `\w+` they could never match and `on` fired inside
// `on-failure` instead.
const SYSTEMD_LITERALS =
  "yes no true false on off simple forking oneshot notify notify-reload dbus idle exec " +
  "always on-failure on-abnormal on-success on-abort on-watchdog " +
  "multi-user.target network-online.target network.target default.target " +
  "graphical.target sysinit.target basic.target sockets.target timers.target " +
  "local-fs.target remote-fs.target shutdown.target " +
  "full strict read-only tmpfs journal inherit null tty kmsg " +
  "control-group mixed process none main all private self " +
  "invisible noaccess ptraceable normal direct continue stop kill";

/** @param {import("highlight.js").HLJSApi} hljs */
function defineSystemd(hljs) {
  const SECTION = {
    className: "section",
    begin: new RegExp(`^\\[(?:${SYSTEMD_SECTIONS.join("|")})\\]`),
    relevance: 10,
  };

  // The full specifier table from systemd.unit(5), not just the instance
  // and path ones.
  const SPECIFIER = {
    className: "template-variable",
    begin: /%[aAbBCdEfgGhHiIjJlLmMnNopPqsStTuUvVwWyY%]/,
    relevance: 0,
  };

  // Durations and sizes carry their unit (`5s`, `1min`, `512M`, `50%`).
  const NUMBER = {
    className: "number",
    begin: /\b\d+(?:\.\d+)?(?:ms|us|ns|min|sec|[smhdwKMGT%])?(?!\w)/,
    relevance: 0,
  };

  const VARIABLE = {
    className: "variable",
    variants: [
      { begin: /\$\{[A-Za-z_][A-Za-z0-9_]*\}/ },
      { begin: /\$[A-Za-z_][A-Za-z0-9_]*/ },
    ],
    relevance: 0,
  };

  const EXEC_PREFIX = {
    className: "operator",
    begin: /[-@+!]+(?=\/)/,
    relevance: 0,
  };

  const KNOWN_KEY = {
    className: "built_in",
    begin: new RegExp(`^(?:${SYSTEMD_KNOWN_KEYS.join("|")})(?=\\s*=)`),
    relevance: 5,
  };

  const KEY = {
    className: "attr",
    begin: /^[A-Za-z][A-Za-z0-9]*(?=\s*=)/,
    relevance: 0,
  };

  return {
    name: "systemd",
    aliases: ["unit", "service"],
    case_insensitive: false,
    keywords: {
      $pattern: /[\w.-]+/,
      literal: SYSTEMD_LITERALS,
    },
    contains: [
      hljs.COMMENT("#", "$"),
      hljs.COMMENT(";", "$"),
      SECTION,
      KNOWN_KEY,
      KEY,
      EXEC_PREFIX,
      SPECIFIER,
      VARIABLE,
      NUMBER,
    ],
  };
}

/** @type {import("highlight.js").LanguageFn} */
function register(hljs) {
  return defineSystemd(hljs);
}

export const systemd = { name: "systemd", register };
export default systemd;
