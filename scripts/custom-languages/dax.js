/** @param {import("highlight.js").HLJSApi} hljs */
function defineDax(hljs) {
  const NUMBER = {
    className: "number",
    variants: [{ begin: /\b\d+(?:\.\d+)?(?:[eE][+-]?\d+)?\b/ }],
    relevance: 0,
  };

  // `dt"2024-01-31"` is the datetime literal form (2022).
  const STRING = {
    className: "string",
    begin: /(?:\bdt)?"/,
    end: /"/,
    contains: [{ begin: /""/, relevance: 0 }],
  };

  // Dotted function families: `INFO.MEASURES()`, `NORM.DIST()`,
  // `PERCENTILE.INC()`, `RANK.EQ()`. The keyword pattern stops at `.`, so
  // these need their own rule.
  const DOTTED_FUNCTION = {
    className: "built_in",
    begin:
      /\b(?:INFO|NORM|T|CHISQ|EXPON|POISSON|BETA|CONFIDENCE|PERCENTILE|PERCENTILEX|PERCENTRANK|RANK)\.[A-Za-z]+(?:\.[A-Za-z]+)?\b/,
    relevance: 0,
  };

  const LINE_COMMENT = {
    className: "comment",
    variants: [hljs.C_LINE_COMMENT_MODE, { begin: /--/, end: /$/ }],
    relevance: 0,
  };

  // A quoted table name is a symbol whether or not a column follows:
  // `ALL ( 'Product' )`. With the old `(?=\[)` lookahead the bare form fell
  // through to the keyword table, which styled `Product` and `Date` as the
  // functions of the same name.
  const QUOTED_TABLE = {
    className: "symbol",
    begin: /'[^'\n]+'/,
    relevance: 0,
  };

  const UNQUOTED_TABLE = {
    className: "symbol",
    begin: /[A-Za-z_][A-Za-z0-9_]*(?=\[)/,
    relevance: 0,
  };

  const MEASURE_REF = {
    className: "variable",
    begin: /\[[^\]]+\]/,
    relevance: 0,
  };

  return {
    name: "DAX",
    aliases: ["dax"],
    case_insensitive: true,
    keywords: {
      keyword: DAX_KEYWORDS,
      built_in: DAX_FUNCTIONS,
      literal: DAX_LITERALS,
    },
    contains: [
      hljs.C_BLOCK_COMMENT_MODE,
      LINE_COMMENT,
      STRING,
      QUOTED_TABLE,
      DOTTED_FUNCTION,
      UNQUOTED_TABLE,
      MEASURE_REF,
      NUMBER,
    ],
  };
}

/** @type {import("highlight.js").LanguageFn} */
function register(hljs) {
  return defineDax(hljs);
}

export const dax = { name: "dax", register };
export default dax;
